"""Отделка иллюстраций перед перекраской в палитры: радужный перелив меди сводится к одному оттенку металла.

Раунд 5. Сначала здесь были ещё плёночное зерно, укороченные блики и погашенные ореолы у стеклянной девушки.
Заказчик увидел в этом размытость и шероховатость, поэтому всё это убрано: резкость и свет исходника не трогаются.
У «Сигнала» отделка не применяется вовсе, его кадры — исходники как есть. Работает в OkLab, вызывается из scenes.py.
"""
import numpy as np

M1 = np.array([[0.4122214708, 0.5363325363, 0.0514459929], [0.2119034982, 0.6806995451, 0.1073969566], [0.0883024619, 0.2817188376, 0.6299787005]])
M2 = np.array([[0.2104542553, 0.7936177850, -0.0040720468], [1.9779984951, -2.4285922050, 0.4505937099], [0.0259040371, 0.7827717662, -0.8086757660]])


def _lin(c):
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def _srgb(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * c ** (1 / 2.4) - 0.055)


def _lch(rgb):
    lab = np.cbrt(_lin(rgb) @ M1.T) @ M2.T
    return lab[..., 0], np.hypot(lab[..., 1], lab[..., 2]), np.arctan2(lab[..., 2], lab[..., 1])


def _rgb(L, C, H):
    lab = np.stack([L, C * np.cos(H), C * np.sin(H)], -1)
    return _srgb(((lab @ np.linalg.inv(M2).T) ** 3) @ np.linalg.inv(M1).T)


def _circ_median(h):
    return np.arctan2(np.median(np.sin(h)), np.median(np.cos(h)))


def matte_scene(rgb):
    """Сцена на белом фоне: перелив металла сводится к одному оттенку. Резкость, блики и фон не трогаются."""
    L, C, H = _lch(rgb)
    metal = np.clip((C - 0.045) / 0.035, 0, 1)
    if (metal > 0.6).any():
        h0 = _circ_median(H[metal > 0.6])
        d = np.angle(np.exp(1j * (H - h0)))
        H = h0 + d * (1 - 0.7 * metal)          # перелив сводится к одному оттенку
        C = C * (1 - 0.12 * metal)
    return _rgb(L, C, H)
