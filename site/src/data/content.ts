/* Неразрывные места для узких экранов: короткое слово держится за следующее, тире — за предыдущее,
   слово через дефис не рвётся (в урезанных шрифтах нет неразрывного дефиса, поэтому после дефиса ставится
   невидимый соединитель слов U+2060) */
export const nb = (s: string) =>
  s
    .replace(/(?<=^|[\s(«])([а-яё]{1,2}|для|без|под|над|при|про|или|что)\s/gi, '$1\u00a0')
    .replace(/ (—|–)/g, '\u00a0$1')
    .replace(/(?<=[A-Za-zА-Яа-яЁё0-9])-(?=[A-Za-zА-Яа-яЁё])/g, '-\u2060');

